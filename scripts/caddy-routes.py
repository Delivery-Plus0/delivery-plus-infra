#!/usr/bin/env python3
"""Caddy rewrites for the dynamic routes of an Expo Router static web export.

Expo writes one HTML file per route, and a dynamic segment keeps its brackets in the file name:
app/(app)/order/[id].tsx becomes order/[id].html. A deep link such as /order/3f2a… has to be
served that file. This prints one `rewrite` per dynamic route, most specific first, for the app's
site block in the Caddyfile (`import /etc/caddy/routes/<app>.caddy`).

Usage: caddy-routes.py <export-dir> > routes/<app>.caddy
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

DYNAMIC = re.compile(r"^\[(\.\.\.)?[^\]]+\]$")


def route_of(relative: Path) -> list[str] | None:
    """Path segments of a route file, or None for files that aren't routes."""
    parts = list(relative.with_suffix("").parts)
    # Route groups such as (app) and (tabs) aren't part of the URL; Expo also writes flattened copies.
    if any(part.startswith("(") for part in parts):
        return None
    if parts and parts[-1] == "index":
        parts = parts[:-1]
    return parts


def pattern_of(segments: list[str]) -> str:
    out = []
    for segment in segments:
        match = DYNAMIC.match(segment)
        if match and match.group(1):  # [...rest] catches one or more segments
            out.append(r"[^?#]+")
        elif match:
            out.append(r"[^/?#]+")
        else:
            out.append(re.escape(segment))
    return "^/" + "/".join(out) + "/?$"


def rules(export_dir: Path) -> list[tuple[str, str]]:
    found = []
    for file in sorted(export_dir.rglob("*.html")):
        relative = file.relative_to(export_dir)
        segments = route_of(relative)
        if not segments or not any(DYNAMIC.match(segment) for segment in segments):
            continue
        found.append((segments, "/" + relative.as_posix()))
    # Static segments before dynamic ones, longer routes first: /order/[id]/receipt before /order/[id].
    found.sort(key=lambda item: (-len(item[0]), [bool(DYNAMIC.match(s)) for s in item[0]]))
    return [(pattern_of(segments), target) for segments, target in found]


def main(argv: list[str]) -> int:
    if len(argv) != 2 or not Path(argv[1]).is_dir():
        print(__doc__.strip().splitlines()[-1], file=sys.stderr)
        return 2
    export_dir = Path(argv[1])
    print(f"# Generated by scripts/caddy-routes.py from {export_dir.name}; do not edit.")
    for index, (pattern, target) in enumerate(rules(export_dir)):
        print(f"@route{index} path_regexp {pattern}")
        print(f'rewrite @route{index} "{target}"')
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
